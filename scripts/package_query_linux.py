"""Inside isolated pinned container: package only approved source/production deps."""

import argparse
import hashlib
import json
import os
import shutil
import sys
import zipfile
from pathlib import Path

SOURCE = Path("/source")
PACKAGE = Path("/tmp/query-package")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--repack", action="store_true")
    args = parser.parse_args()
    if args.repack:
        PACKAGE.mkdir(parents=True)
        with zipfile.ZipFile("/build/query-runtime.zip") as archive:
            if sum(i.file_size for i in archive.infolist()) >= 250 * 1024 * 1024:
                raise ValueError("EXISTING_PACKAGE_EXPANSION_LIMIT")
            for info in archive.infolist():
                relative = Path(info.filename)
                if relative.is_absolute() or ".." in relative.parts or info.flag_bits & 1:
                    raise ValueError("EXISTING_PACKAGE_UNSAFE_MEMBER")
                if relative.parts[0] in {"app", "configs", "data"}:
                    continue
                target = PACKAGE / relative
                target.parent.mkdir(parents=True, exist_ok=True)
                with archive.open(info) as source, target.open("wb") as out:
                    shutil.copyfileobj(source, out)
    inventory = json.loads(Path("/build/source_inventory.json").read_bytes())
    for relative, digest in inventory.items():
        path = SOURCE / relative
        if not path.resolve().is_relative_to(SOURCE) or hashlib.sha256(path.read_bytes()).hexdigest() != digest:
            raise ValueError("SOURCE_INVENTORY_CHANGED")
        target = PACKAGE / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, target)
    # Wheel executable wrappers and generated bytecode do not belong in a query package.
    files = sorted(p for p in PACKAGE.rglob("*") if p.is_file() and p.suffix != ".pyc"
                   and "__pycache__" not in p.parts and p.relative_to(PACKAGE).parts[0] != "bin")
    uncompressed = sum(p.stat().st_size for p in files)
    if uncompressed >= 250 * 1024 * 1024:
        raise ValueError("QUERY_ZIP_UNCOMPRESSED_TOO_LARGE")
    if any(p.is_symlink() or not p.resolve().is_relative_to(PACKAGE) for p in files):
        raise ValueError("QUERY_ZIP_UNSAFE_PATH")
    sys.path.insert(0, str(PACKAGE))
    os.chdir(PACKAGE)
    import numpy
    import onnxruntime
    import tokenizers

    from app.cloud_preflight import handler
    from app.generation import GeneratedAnswer
    from app.ingestion.text import ProxyTokenizer
    from app.query_handler import handler as query_handler

    assert callable(handler) and callable(query_handler) and GeneratedAnswer and ProxyTokenizer().count("source text") > 0
    archive = Path("/build/query-runtime.zip")
    with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=6) as out:
        for path in files:
            info = zipfile.ZipInfo(path.relative_to(PACKAGE).as_posix(), date_time=(1980, 1, 1, 0, 0, 0))
            info.create_system, info.external_attr = 3, 0o644 << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            out.writestr(info, path.read_bytes(), compresslevel=6)
    digest = hashlib.file_digest(archive.open("rb"), "sha256").hexdigest()
    report = {"status": "PASS", "python": sys.version.split()[0], "package_bytes": archive.stat().st_size,
        "uncompressed_bytes": uncompressed, "files": len(files), "sha256": digest,
        "numpy": numpy.__version__, "onnxruntime": onnxruntime.__version__, "tokenizers": tokenizers.__version__,
        "local_imports": "PASS", "proxy_tokenizer_asset": "PASS", "model_weights_in_zip": False}
    Path("/build/package_report.json").write_text(json.dumps(report, indent=2) + "\n")


if __name__ == "__main__":
    main()
